import { chromium } from '@playwright/test';
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
await page.goto('http://localhost:4173/?db=ss-' + Date.now());
await page.getByRole('button', { name: 'Enter' }).click();
await page.waitForFunction(() => window.atrium?.session?.view);
await page.evaluate(() => window.atrium.session.search.ready);
await page.mouse.move(5, 5);
await page.keyboard.press('Control+k');
await page.getByLabel('Search', { exact: true }).fill('crow');
await page.waitForTimeout(500);
await page.screenshot({ path: 'test-results/launcher.png' });
await page.keyboard.press('Control+Enter');
await page.waitForFunction(() => window.atrium.session.view.room.kind === 'search');
await page.evaluate(() => window.atrium.session.view.whenSettled());
await page.evaluate(() => { const s = window.atrium.session; s.player.place(0, 1.5, 0); s.player.yaw = 0.4; s.world.renderOnce(); });
await page.waitForTimeout(600);
await page.screenshot({ path: 'test-results/searchroom.png' });
await browser.close();
