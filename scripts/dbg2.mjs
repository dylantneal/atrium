import { chromium } from '@playwright/test';
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:4173/?db=dbg2-' + Date.now());
await page.getByRole('button', { name: 'Enter' }).click();
await page.waitForFunction(() => window.atrium?.session?.view);
await page.evaluate(() => window.atrium.session.search.ready);
await page.keyboard.press('Control+k');
await page.getByLabel('Search', { exact: true }).fill('animatik');
await page.waitForTimeout(400);
await page.keyboard.press('Enter');
await page.waitForFunction(() => window.atrium.session.view.room.title === 'Animatic');
await page.keyboard.press('Control+k');
await page.getByLabel('Search', { exact: true }).fill('crow animatic 02');
await page.waitForTimeout(400);
console.log('rows', await page.getByRole('option').allInnerTexts());
console.log('selected', await page.getByRole('option').evaluateAll((els) => els.map((e) => e.getAttribute('aria-selected'))));
console.log('before', await page.evaluate(() => ({ room: window.atrium.session.view.room.title, cur: window.atrium.session.currentId })));
await page.keyboard.press('Enter');
await page.waitForTimeout(800);
console.log('after', await page.evaluate(() => ({ room: window.atrium.session.view.room.title, focus: window.atrium.ui.get().focus })));
await browser.close();
