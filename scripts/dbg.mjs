import { chromium } from '@playwright/test';
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('console', (m) => console.log('console', m.type(), m.text()));
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:4173/?db=dbg-' + Date.now());
await page.getByRole('button', { name: 'Enter' }).click();
await page.waitForFunction(() => window.atrium?.session?.view);
const r = await page.evaluate(async () => {
  const a = window.atrium; const s = a.session;
  const find = async (p) => { let id = a.vfs.rootId; for (const part of p.split('/')) id = (await a.vfs.list(id)).find((k) => k.name === part).id; return id; };
  await s.enter(await find('Crow Short Film/Storyboards'), null, true); await s.view.whenSettled();
  const it = [...s.items.values()][0];
  s.inventory.pickUp(it.id);
  await s.enter(await find('Crow Short Film/Renders'), null, true); await s.view.whenSettled();
  const out = { free: s.view.freeSpotCount, ref: s.view.ghostRef(0), sel: s.inventory.selectedId };
  const ref = s.view.ghostRef(0);
  const pos = s.view.slotWorldPos(ref.side, ref.slot);
  s.player.place(0, 0, 0);
  s.player.yaw = Math.atan2(-(pos.x), -(pos.z)); s.player.pitch = 0; s.world.renderOnce();
  const v = pos.clone().project(s.camera);
  out.ndc = [v.x, v.y, v.z];
  out.pick = JSON.stringify(s.view.pick(s.camera, v.x, v.y, 20));
  out.pickCenter = JSON.stringify(s.view.pick(s.camera, 0, 0, 20));
  await s.primary(v.x, v.y, false);
  out.toasts = a.bus.currentToasts.map((t) => t.text);
  return out;
});
console.log(JSON.stringify(r, null, 1));
await browser.close();
